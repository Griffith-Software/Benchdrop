const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('benchdrop', {
  pickZip: (opts) => ipcRenderer.invoke('pick-zip', opts || {}),
  loadZip: (zipPath, forceFresh = false) => ipcRenderer.invoke('load-zip', { zipPath, forceFresh }),
  loadUrl: (url) => ipcRenderer.invoke('load-url', { url }),
  getRecents: () => ipcRenderer.invoke('get-recents'),
  removeRecent: (p) => ipcRenderer.invoke('remove-recent', { path: p }),
  runScripts: (projectDir, scriptNames) => ipcRenderer.invoke('run-scripts', { projectDir, scriptNames }),
  serveHtml: (projectDir, entryFile) => ipcRenderer.invoke('serve-html', { projectDir, entryFile }),
  runRuntime: (projectDir, command, runtimeLabel, oneShot) =>
    ipcRenderer.invoke('run-runtime', { projectDir, command, runtimeLabel, oneShot }),
  runPython: (projectDir, entryFile, entryArgs, installRequirements) =>
    ipcRenderer.invoke('run-python', { projectDir, entryFile, entryArgs, installRequirements }),
  stopApp: () => ipcRenderer.invoke('stop-app'),
  forceCleanReinstall: () => ipcRenderer.invoke('clean-reinstall'),
  resetProject: () => ipcRenderer.invoke('reset-project'),
  sendInput: (procId, text) => ipcRenderer.invoke('send-input', { procId, text }),
  runCommand: (command) => ipcRenderer.invoke('run-command', { command }),
  freePort: (port, retry = true) => ipcRenderer.invoke('free-port', { port, retry }),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  clearCache: () => ipcRenderer.invoke('clear-cache'),
  capture: (webContentsId, mode, rect) => ipcRenderer.invoke('capture', { webContentsId, mode, rect }),
  openShotsFolder: () => ipcRenderer.invoke('open-shots-folder'),
  copyText: (text) => ipcRenderer.invoke('copy-text', { text }),
  getSettings: () => ipcRenderer.invoke('get-settings'),
  phonePreview: (url) => ipcRenderer.invoke('phone-preview', { url }),
  stopPhonePreview: () => ipcRenderer.invoke('stop-phone-preview'),
  setLiveReload: (enabled) => ipcRenderer.invoke('set-live-reload', { enabled }),
  setTrace: (enabled, webContentsId, announce = false) =>
    ipcRenderer.invoke('set-trace', { enabled, webContentsId, announce }),
  openProjectFolder: () => ipcRenderer.invoke('open-project-folder'),
  codeList: () => ipcRenderer.invoke('code-list'),
  codeRead: (p) => ipcRenderer.invoke('code-read', { path: p }),
  codeWrite: (p, content) => ipcRenderer.invoke('code-write', { path: p, content }),
  codeExport: () => ipcRenderer.invoke('code-export'),
  runNative: (projectDir, exe, args) => ipcRenderer.invoke('run-native', { projectDir, exe, args }),
  androidTargets: (projectDir) => ipcRenderer.invoke('android-targets', { projectDir }),
  androidLocate: (what, projectDir) => ipcRenderer.invoke('android-locate', { what, projectDir }),
  runAndroid: (projectDir, target, build) => ipcRenderer.invoke('run-android', { projectDir, target, build }),
  androidInput: (ev) => ipcRenderer.invoke('android-input', ev),
  androidStudioPage: () => ipcRenderer.invoke('android-studio-page'),
  androidPhone: (projectDir) => ipcRenderer.invoke('android-phone', { projectDir }),
  androidPhoneStop: () => ipcRenderer.invoke('android-phone-stop'),
  nativeCapture: (rect) => ipcRenderer.invoke('native-capture', { rect }),
  nativeFrame: () => ipcRenderer.invoke('native-frame'),
  nativeSource: () => ipcRenderer.invoke('native-source'),
  nativeDock: (bounds) => ipcRenderer.invoke('native-dock', { bounds }),
  nativeMove: (bounds) => ipcRenderer.invoke('native-move', { bounds }),
  nativeShow: (visible, front) => ipcRenderer.invoke('native-show', { visible, front }),
  nativeUndock: () => ipcRenderer.invoke('native-undock'),
  nativeRestart: () => ipcRenderer.invoke('native-restart'),
  nativeSelfCheck: () => ipcRenderer.invoke('native-self-check'),
  autotestStart: (opts) => ipcRenderer.invoke('autotest-start', opts),
  autotestStop: () => ipcRenderer.invoke('autotest-stop'),
  openPath: (target) => ipcRenderer.invoke('open-path', { target }),

  pathForFile: (file) => webUtils.getPathForFile(file),

  onLog: (cb) => ipcRenderer.on('log', (_e, payload) => cb(payload)),
  onConnectorRequest: (cb) => ipcRenderer.on('connector-request', (_e, payload) => cb(payload)),
  connectorReply: (id, result, error) => ipcRenderer.invoke('connector-reply', { id, result, error }),
  connectorSetup: () => ipcRenderer.invoke('connector-setup'),
  connectorInstallDesktop: () => ipcRenderer.invoke('connector-install-desktop'),
  connectorCopy: (value) => ipcRenderer.invoke('connector-copy', { value }),
  onStatus: (cb) => ipcRenderer.on('status', (_e, payload) => cb(payload)),
  onProcs: (cb) => ipcRenderer.on('procs', (_e, payload) => cb(payload)),
  onTheme: (cb) => ipcRenderer.on('theme', (_e, payload) => cb(payload)),
  onMenu: (cb) => ipcRenderer.on('menu', (_e, payload) => cb(payload)),
});
